"""PDF document templates: the built-in ones, administrator edits of them, and users' own templates.

Who may do what (as for custom nodes, src/admin.py):

- built-in templates (``templates/``) are used by everyone; administrators can edit them (LaTeX, fields, name,
  description) with version history and restore; other users can view and duplicate them;
- every logged-in user adds, edits and deletes their own templates — always **private** (only that user's chats);
- administrators switch their templates **global** (on/off): a global template is offered in everyone's chats,
  and only administrators edit or delete it.

A template is written either with the block builder (``mode: "blocks"``: title, sender, recipient, paragraphs,
lists, tables, signature …, turned into LaTeX with the same fonts and Polish setup as the built-in templates) or
directly in LaTeX (``mode: "latex"``). Fields are ``{{NAME}}`` placeholders; ``{{NAME|lista}}`` turns a
multi-line value into list items, ``{{NAME|tabela:N}}`` into table rows of N columns (cells separated by
``|`` or ``;``), ``{{NAME|linie}}`` keeps its line breaks and ``{{NAME|akapity}}`` makes paragraphs of
blank-line-separated parts. The builder adds ``linie``/``akapity`` itself where they belong (address blocks,
signature, paragraphs). Values are escaped when the document is filled (src/agent_tools.py).

Every template must compile (in the sandbox, with the fields' example values) before it is saved; the preview
uses the same path. Storage, under the data directory and used by the UI only:
``custom_templates/<owner>/<id>/`` (``template.json`` + ``template.tex``) and ``template_overrides/<id>.json``
(+ ``<id>.tex``, the version in force) for edited built-ins. ``catalog(None)`` — evaluation runs, no login —
is exactly the repository's templates.
"""

