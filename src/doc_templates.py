BLOCK_TYPES = {
    "title": "Tytuł", "heading": "Nagłówek sekcji", "paragraph": "Akapit", "sender": "Nadawca",
    "recipient": "Odbiorca", "place_date": "Miejsce i data", "list": "Lista", "table": "Tabela",
    "signature": "Podpis", "spacer": "Odstęp", "page_break": "Nowa strona", "footer": "Stopka",
}
_SPECIALS = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
             "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def escape_literal(text: str) -> str:
    """Escape the template author's literal text; ``{{FIELD}}`` placeholders stay as they are."""
    out, last = [], 0
    for m in PLACEHOLDER.finditer(text or ""):
        out.append("".join(_SPECIALS.get(c, c) for c in text[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append("".join(_SPECIALS.get(c, c) for c in (text or "")[last:]))
    return "".join(out)


def _with_filter(latex: str, kind: str) -> str:
    """Give plain ``{{FIELD}}`` placeholders a filter (multi-line values keep their shape in this block)."""
    return PLACEHOLDER.sub(lambda m: m.group(0) if m.group(2) else "{{" + m.group(1) + "|" + kind + "}}", latex)


def _lines(text: str) -> str:
    """Literal multi-line text: a line break per line; fields keep their own line breaks."""
    rows = [escape_literal(r) for r in (text or "").splitlines() if r.strip()]
    return _with_filter(r"\\".join(rows), "linie")


def _paragraphs(text: str) -> str:
    parts = [p for p in re.split(r"\n\s*\n", (text or "").strip()) if p.strip()]
    return _with_filter("\n\n".join(r"\\".join(escape_literal(r) for r in p.splitlines()) for p in parts), "akapity")


def render_block(block: dict) -> str:
    kind = block.get("type")
    text = str(block.get("text", ""))
    field = str(block.get("field", ""))
    if kind == "title":
        return "\\begin{center}\n{\\LARGE\\bfseries " + _lines(text) + "\\par}\n\\end{center}\n\\vspace{4mm}"
    if kind == "heading":
        return ("\\subsection*{" if str(block.get("level")) == "2" else "\\section*{") + escape_literal(text.strip()) + "}"
    if kind == "paragraph":
        env = {"center": "center", "right": "flushright", "left": "flushleft"}.get(block.get("align", ""))
        body = _paragraphs(text)
        return f"\\begin{{{env}}}\n{body}\n\\end{{{env}}}" if env else body
    if kind == "sender":
        return "\\noindent\n" + _lines(text)
    if kind == "recipient":
        return "\\hfill\\begin{tabular}[t]{@{}l@{}}\n" + _lines(text) + "\n\\end{tabular}\n\\par\\vspace{6mm}"
    if kind == "place_date":
        return "\\begin{flushright}\n" + _lines(text) + "\n\\end{flushright}"
    if kind == "list":
        env = "enumerate" if block.get("style") == "numbers" else "itemize"
        return f"\\begin{{{env}}}\n{{{{{field}|lista}}}}\n\\end{{{env}}}"
    if kind == "table":
        headers = [h.strip() for h in re.split(r"[;|]", str(block.get("columns", ""))) if h.strip()] or ["Kolumna"]
        n = len(headers)
        head = " & ".join("\\textbf{" + escape_literal(h) + "}" for h in headers)
        spec = "|" + "|".join(["X"] * n) + "|"
        # every filled row ends with its own \\hline (src/agent_tools.py, filter "tabela")
        return (f"\\par\\smallskip\n\\begin{{tabularx}}{{\\linewidth}}{{{spec}}}\n\\hline\n{head} \\\\\n\\hline\n"
                f"{{{{{field}|tabela:{n}}}}}\n\\end{{tabularx}}\n\\par\\smallskip")
    if kind == "signature":  # {{PODPIS_SLOT}}: blank place or the user's scan, chosen in the form (src/signatures.py)
        return ("\\vspace{4mm}\n\\begin{flushright}\n\\begin{tabular}{c}\n{{PODPIS_SLOT}}\\\\\n\\rule{6cm}{0.4pt}\\\\\n"
                + _lines(text) + "\n\\end{tabular}\n\\end{flushright}")
    if kind == "spacer":
        return "\\vspace{" + {"small": "4mm", "large": "20mm"}.get(block.get("size", ""), "10mm") + "}"
    if kind == "page_break":
        return "\\newpage"
    if kind == "footer":
        return "\\vfill\n\\begin{center}\n\\footnotesize " + _lines(text) + "\n\\end{center}"
    raise TemplateError(f"Nieznany rodzaj bloku: {kind!r}")


def render_blocks(blocks: list[dict]) -> str:
    body = "\n\n".join(render_block(b) for b in blocks)
    return PREAMBLE + "\n\\begin{document}\n\n" + body + "\n\n\\end{document}\n"


# --------------------------------------------------------------------------- drafts and checks

RESERVED_FIELDS = {"PODPIS_SLOT"}  # the signature place (src/signatures.py), not a field the model fills


def used_fields(latex: str) -> list[str]:
    names = []
    for m in PLACEHOLDER.finditer(latex or ""):
        if m.group(1) not in names and m.group(1) not in RESERVED_FIELDS:
            names.append(m.group(1))
    return names


def normalise_draft(data: dict) -> dict:
    """The parts of a template a client may send, cleaned; raises TemplateError with every problem found."""
    problems = []
    tid = str(data.get("id", "")).strip()
    name = str(data.get("name", "")).strip()
    description = str(data.get("description", "")).strip()
    mode = data.get("mode", "blocks")
    if not ID.match(tid):
        problems.append("Identyfikator: 3–41 znaków, małe litery bez polskich znaków, cyfry i _, zaczyna się literą.")
    if not name or len(name) > 80:
        problems.append("Nazwa: od 1 do 80 znaków.")
    if not description or len(description) > 600:
        problems.append("Opis dla modelu: od 1 do 600 znaków (model wybiera szablon na podstawie opisu).")
    if mode not in ("blocks", "latex"):
        problems.append("Tryb: bloki albo LaTeX.")
    fields = {}
    raw_fields = data.get("parameters") or {}
    if not isinstance(raw_fields, dict) or not raw_fields:
        problems.append("Dodaj co najmniej jedno pole.")
        raw_fields = {}
    for key, spec in raw_fields.items():
        spec = spec if isinstance(spec, dict) else {}
        if not FIELD.match(str(key)):
            problems.append(f"Pole {key!r}: nazwa wielkimi literami, cyframi i _ (np. NAZWA_KLIENTA).")
            continue
        if key in RESERVED_FIELDS:
            problems.append(f"Pole {key}: ta nazwa oznacza miejsce na podpis — wstaw ją w treść, ale nie dodawaj jako pola.")
            continue
        label = str(spec.get("description", "")).strip()
        if not label or len(label) > 120:
            problems.append(f"Pole {key}: etykieta od 1 do 120 znaków.")
        fields[key] = {"description": label, "example": str(spec.get("example", ""))[:4000],
                       "required": bool(spec.get("required", True)), "multiline": bool(spec.get("multiline", False))}
    blocks = []
    if mode == "blocks":
        raw_blocks = data.get("blocks") or []
        if not isinstance(raw_blocks, list) or not raw_blocks:
            problems.append("Dodaj co najmniej jeden blok.")
            raw_blocks = []
        for i, b in enumerate(raw_blocks[:200]):
            b = b if isinstance(b, dict) else {}
            if b.get("type") not in BLOCK_TYPES:
                problems.append(f"Blok {i + 1}: nieznany rodzaj.")
                continue
            clean = {k: v for k, v in b.items() if k in ("type", "text", "field", "align", "level", "style", "columns", "size")}
            clean = {k: (v[:20_000] if isinstance(v, str) else v) for k, v in clean.items()}
            if b["type"] in ("list", "table") and clean.get("field") not in fields:
                problems.append(f"Blok {i + 1} ({BLOCK_TYPES[b['type']]}): wybierz pole z listy pól.")
            blocks.append(clean)
        latex = render_blocks(blocks) if not problems else ""
    else:
        latex = str(data.get("latex", "")).replace("\r\n", "\n")
        if len(latex) > MAX_LATEX:
            problems.append("LaTeX: najwyżej 200 000 znaków.")
        for needed in ("\\documentclass", "\\begin{document}", "\\end{document}"):
            if needed not in latex:
                problems.append(f"LaTeX: brakuje {needed}.")
    if latex:
        undefined = [f for f in used_fields(latex) if f not in fields]
        if undefined:
            problems.append("Szablon używa niezdefiniowanych pól: " + ", ".join(undefined) + ". Dodaj je na liście pól.")
    if problems:
        raise TemplateError("\n".join(problems))
    return {"id": tid, "name": name, "description": description, "mode": mode, "blocks": blocks, "latex": latex,
            "parameters": fields}


def check_report(draft: dict) -> dict:
    """Warnings that do not stop a save (fields defined but never used), and the template's LaTeX (the builder's
    output: the panel switches a block template to LaTeX mode with it)."""
    used = set(used_fields(draft["latex"]))
    return {"unused_fields": [f for f in draft["parameters"] if f not in used], "latex": draft["latex"]}


# --------------------------------------------------------------------------- built-in templates

def _builtin_meta() -> dict:
    return json.loads(BUILTIN_META.read_text(encoding="utf-8")).get("templates", {})


def _override_file(tid: str) -> Path:
    return overrides_dir() / f"{tid}.json"


def builtin_history(tid: str) -> list[dict]:
    path = _override_file(tid)
    return json.loads(path.read_text(encoding="utf-8")).get("history", []) if path.is_file() else []


def _builtin(tid: str, with_overrides: bool) -> Optional[dict]:
    meta = _builtin_meta().get(tid)
    if meta is None:
        return None
    info = {"id": tid, "name": meta["name"], "description": meta["description"], "parameters": meta.get("parameters", {}),
            "path": str(BUILTIN_DIR / meta["file"]), "kind": "builtin", "mode": "latex", "overridden": False}
    if meta.get("compact_below_chars"):
        info["compact_below_chars"] = meta["compact_below_chars"]
    if with_overrides:
        history = builtin_history(tid)
        current = overrides_dir() / f"{tid}.tex"
        if history and history[-1].get("template") and current.is_file():
            t = history[-1]["template"]
            info.update(name=t["name"], description=t["description"], parameters=t["parameters"], path=str(current),
                        overridden=True)
    return info


# --------------------------------------------------------------------------- custom templates

def _custom_index() -> dict[str, tuple[Path, dict]]:
    index = {}
    root = custom_dir()
    for meta in sorted(root.glob("*/*/template.json")) if root.is_dir() else []:
        try:
            data = json.loads(meta.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if data.get("id") == meta.parent.name and (meta.parent / "template.tex").is_file():
            index[data["id"]] = (meta.parent, data)
    return index


def _owner(data: dict) -> str:
    return data.get("config", {}).get("owner", "")


def _is_global(data: dict) -> bool:
    return bool(data.get("config", {}).get("global"))


def can_use(user: Optional[str], data: dict) -> bool:
    return _is_global(data) or (user is not None and _owner(data) == user)


def can_edit(user: Optional[str], data: dict) -> bool:
    return _admin().is_admin(user) if _is_global(data) else (user is not None and _owner(data) == user)


def _custom_info(folder: Path, data: dict) -> dict:
    return {"id": data["id"], "name": data["name"], "description": data["description"], "parameters": data["parameters"],
            "path": str(folder / "template.tex"), "kind": "custom", "mode": data.get("mode", "blocks")}


# --------------------------------------------------------------------------- catalog (used when documents are made)

def catalog(user: Optional[str]) -> dict:
    """``{"templates": {id: info}}`` for a user: built-in (with administrator edits), global and their own templates.

    ``user=None`` (evaluation runs, no login): exactly the repository's templates.
    """
    templates = {tid: _builtin(tid, with_overrides=user is not None) for tid in _builtin_meta()}
    if user is not None:
        for tid, (folder, data) in _custom_index().items():
            if can_use(user, data):
                templates[tid] = _custom_info(folder, data)
    return {"templates": templates}


def custom_ids(user: Optional[str]) -> set[str]:
    return {tid for tid, info in catalog(user)["templates"].items() if info["kind"] == "custom"}


def custom_hint(text: str, user: Optional[str]) -> Optional[str]:
    """A custom template the request names (by id or name), e.g. „według szablonu Oferta handlowa”."""
    lower = (text or "").lower()
    best = None
    for tid, info in catalog(user)["templates"].items():
        if info["kind"] != "custom":
            continue
        for needle in (tid.lower(), tid.replace("_", " ").lower(), info["name"].lower()):
            if len(needle) >= 4 and needle in lower and (best is None or len(needle) > best[1]):
                best = (tid, len(needle))
    return best[0] if best else None


# --------------------------------------------------------------------------- preview and compile check

def example_values(parameters: dict) -> dict:
    return {k: (v.get("example") or f"[{v.get('description') or k}]") for k, v in parameters.items()}


def preview(data: dict, user: str, render: bool = True) -> dict:
    """Compile a draft with the fields' example values in the sandbox; returns pages (PNG data URLs) or the error."""
    from src import run_context
    from src.agent_tools import _fill_template, tool_generate_pdf

    draft = normalise_draft(data)
    lock = _preview_locks.setdefault(user, threading.Lock())
    session = f"tplpreview_{re.sub(r'[^a-z0-9]', '_', user.lower())[:20]}_{uuid.uuid4().hex[:8]}"
    started = time.monotonic()
    with lock, run_context.use_context(session_id=session, user=user):
        workspace = run_context.workspace_dir()
        try:
            from src import signatures

            latex, _mode = signatures.fill_slot(draft["latex"], "blank", None, None)  # preview: the blank place
            filled = _fill_template(latex, example_values(draft["parameters"]))
            result = tool_generate_pdf(filled, "podglad.tex")
            ms = round((time.monotonic() - started) * 1000)
            if not result.startswith("SUKCES"):
                return {"ok": False, "ms": ms, "error": result.split("\n", 1)[0], "log": result, **check_report(draft)}
            pages = []
            if render:
                from src import source_view

                pdf = workspace / "podglad.pdf"
                try:
                    sizes = source_view.pdf_page_sizes(pdf)
                    for n, (w, h) in enumerate(sizes[:MAX_PREVIEW_PAGES], 1):
                        png = source_view.render_pdf_page(pdf, n, scale=1.3)
                        pages.append({"n": n, "ratio": round(h / w, 4),
                                      "src": "data:image/png;base64," + base64.b64encode(png).decode("ascii")})
                    total = len(sizes)
                except Exception as exc:  # e.g. the test sandbox writes a dummy PDF
                    return {"ok": True, "ms": ms, "pages": [], "page_count": 0, "render_error": str(exc), **check_report(draft)}
                return {"ok": True, "ms": ms, "pages": pages, "page_count": total, **check_report(draft)}
            return {"ok": True, "ms": ms, "pages": [], **check_report(draft)}
        finally:
            shutil.rmtree(workspace, ignore_errors=True)


def _must_compile(data: dict, user: str) -> None:
    result = preview(data, user, render=False)
    if not result["ok"]:
        raise TemplateError("Szablon się nie kompiluje — popraw go i sprawdź podgląd.\n" + result["log"][:3000])


# --------------------------------------------------------------------------- listing and details for the panel

def _taken_ids() -> set[str]:
    return set(_builtin_meta()) | set(_custom_index())


def list_templates(user: str) -> list[dict]:
    admin = _admin()
    result = []
    for tid in _builtin_meta():
        info = _builtin(tid, with_overrides=True)
        result.append({"id": tid, "name": info["name"], "description": info["description"], "kind": "builtin",
                       "overridden": info["overridden"], "fields": len(info["parameters"]), "editable": admin.is_admin(user)})
    for tid, (folder, data) in _custom_index().items():
        if not can_use(user, data):
            continue
        cfg = data.get("config", {})
        result.append({"id": tid, "name": data["name"], "description": data["description"], "kind": "custom",
                       "mode": data.get("mode", "blocks"), "global": _is_global(data), "owner": cfg.get("owner"),
                       "mine": cfg.get("owner") == user, "editable": can_edit(user, data), "fields": len(data["parameters"]),
                       "can_share": admin.is_admin(user) and (cfg.get("owner") == user or _is_global(data))})
    return result


def get_template(tid: str, user: str) -> dict:
    admin = _admin()
    info = _builtin(tid, with_overrides=True)
    if info is not None:
        history = builtin_history(tid)
        return {"id": tid, "kind": "builtin", "name": info["name"], "description": info["description"], "mode": "latex",
                "latex": Path(info["path"]).read_text(encoding="utf-8"), "parameters": info["parameters"], "blocks": [],
                "overridden": info["overridden"], "editable": admin.is_admin(user),
                "history": [{"ts": h["ts"], "user": h["user"], "restored": h.get("template") is None} for h in history][::-1]}
    folder, data = _custom(tid, user)
    cfg = data.get("config", {})
    return {"id": tid, "kind": "custom", "name": data["name"], "description": data["description"],
            "mode": data.get("mode", "blocks"), "blocks": data.get("blocks", []),
            "latex": (folder / "template.tex").read_text(encoding="utf-8"), "parameters": data["parameters"],
            "global": _is_global(data), "owner": cfg.get("owner"), "mine": cfg.get("owner") == user,
            "editable": can_edit(user, data), "can_share": admin.is_admin(user) and (cfg.get("owner") == user or _is_global(data)),
            "config": {k: cfg[k] for k in ("created_by", "created_at", "updated_by", "updated_at") if k in cfg}}


def _custom(tid: str, user: str) -> tuple[Path, dict]:
    found = _custom_index().get(tid)
    if found is None or not can_use(user, found[1]):
        raise TemplateError("Nie ma takiego szablonu.")
    return found


# --------------------------------------------------------------------------- create, edit, share, delete

def _write(folder: Path, draft: dict, config: dict) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "template.tex").write_text(draft["latex"], encoding="utf-8")
    record = {k: draft[k] for k in ("id", "name", "description", "mode", "blocks", "parameters")}
    record["config"] = config
    tmp = folder / "template.json.tmp"
    tmp.write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(folder / "template.json")


def create_template(data: dict, user: str) -> dict:
    admin = _admin()
    with _lock:
        draft = normalise_draft(data)
        make_global = bool(data.get("global"))
        if make_global and not admin.is_admin(user):
            raise TemplateError("Tylko administrator może udostępnić szablon wszystkim użytkownikom.")
        if draft["id"] in _taken_ids():
            raise TemplateError(f"Identyfikator {draft['id']!r} jest już zajęty przez inny szablon.")
        _must_compile(data, user)
        folder = custom_dir() / admin.owner_folder(user) / draft["id"]
        _write(folder, draft, {"owner": user, "global": make_global, "created_by": user, "created_at": admin.now()})
        admin.audit(user, "template_created", draft["id"], f"{draft['name']}; {'globalny' if make_global else 'prywatny'}; "
                                                           f"tryb {draft['mode']}")
        return {**get_template(draft["id"], user), **check_report(draft)}


def update_template(tid: str, data: dict, user: str) -> dict:
    admin = _admin()
    with _lock:
        if tid in _builtin_meta():
            return _save_builtin(tid, data, user)
        folder, old = _custom(tid, user)
        if not can_edit(user, old):
            raise TemplateError("Ten szablon może zmienić tylko jego autor (szablon globalny — administrator).")
        draft = normalise_draft({**data, "id": tid})
        _must_compile({**data, "id": tid}, user)
        config = {**old.get("config", {}), "updated_by": user, "updated_at": admin.now()}
        _write(folder, draft, config)
        admin.audit(user, "template_updated", tid, f"{draft['name']}; tryb {draft['mode']}")
        return {**get_template(tid, user), **check_report(draft)}


def _save_builtin(tid: str, data: dict, user: str) -> dict:
    admin = _admin()
    if not admin.is_admin(user):
        raise TemplateError("Wbudowane szablony zmienia tylko administrator. Użyj „Duplikuj”, aby zrobić własną wersję.")
    draft = normalise_draft({**data, "id": tid, "mode": "latex"})
    missing = [f for f, spec in _builtin_meta()[tid].get("parameters", {}).items() if f not in draft["parameters"]]
    if missing:  # the model's prompt and the alias map rely on the built-in field names
        raise TemplateError("Wbudowany szablon musi zachować swoje pola: " + ", ".join(missing))
    _must_compile({**data, "id": tid, "mode": "latex"}, user)
    folder = overrides_dir()
    folder.mkdir(parents=True, exist_ok=True)
    history = builtin_history(tid) + [{"ts": admin.now(), "user": user, "template": {
        k: draft[k] for k in ("name", "description", "parameters", "latex")}}]
    (folder / f"{tid}.tex").write_text(draft["latex"], encoding="utf-8")
    _override_file(tid).write_text(json.dumps({"id": tid, "history": history}, ensure_ascii=False, indent=1), encoding="utf-8")
    admin.audit(user, "template_builtin_saved", tid, draft["name"])
    return {**get_template(tid, user), **check_report(draft)}


def restore_builtin(tid: str, user: str) -> dict:
    admin = _admin()
    with _lock:
        if tid not in _builtin_meta():
            raise TemplateError("To nie jest wbudowany szablon.")
        if not admin.is_admin(user):
            raise TemplateError("Tylko administrator może przywrócić wbudowany szablon.")
        if builtin_history(tid) and builtin_history(tid)[-1].get("template"):
            history = builtin_history(tid) + [{"ts": admin.now(), "user": user, "template": None}]
            _override_file(tid).write_text(json.dumps({"id": tid, "history": history}, ensure_ascii=False, indent=1), encoding="utf-8")
            (overrides_dir() / f"{tid}.tex").unlink(missing_ok=True)
            admin.audit(user, "template_builtin_restored", tid, "przywrócono domyślny")
        return get_template(tid, user)


def set_global(tid: str, value: bool, user: str) -> dict:
    admin = _admin()
    with _lock:
        if not admin.is_admin(user):
            raise TemplateError("Tylko administrator może to zrobić.")
        folder, data = _custom(tid, user)
        if not (_owner(data) == user or _is_global(data)):
            raise TemplateError("Udostępnić można tylko własny szablon.")
        data.setdefault("config", {})["global"] = bool(value)
        tmp = folder / "template.json.tmp"
        tmp.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        tmp.replace(folder / "template.json")
        admin.audit(user, "template_shared" if value else "template_unshared", tid,
                    "dostępny dla wszystkich" if value else "tylko dla autora")
        return {"id": tid, "global": bool(value)}


def delete_template(tid: str, user: str) -> dict:
    admin = _admin()
    with _lock:
        if tid in _builtin_meta():
            raise TemplateError("Wbudowanego szablonu nie można usunąć (administrator może przywrócić jego domyślną wersję).")
        folder, data = _custom(tid, user)
        if not can_edit(user, data):
            raise TemplateError("Ten szablon może usunąć tylko jego autor (szablon globalny — administrator).")
        folder = folder.resolve()
        if folder.parent.parent != custom_dir().resolve():
            raise TemplateError("Niepoprawna ścieżka szablonu.")
        shutil.rmtree(folder)
        admin.audit(user, "template_deleted", tid)
        return {"deleted": tid}


